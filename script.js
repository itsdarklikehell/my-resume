        // Escape voor waarden die uit de GitHub-API komen (beschrijvingen, topics,
        // repo-namen). Die zijn door de gebruiker zelf te beïnvloeden, dus we
        // renderen ze nooit ruw in innerHTML.
        function escapeHtml(v) {
            if (v == null) return '';
            return String(v)
                .replace(/&/g, '&amp;')
                .replace(/</g, '&lt;')
                .replace(/>/g, '&gt;')
                .replace(/"/g, '&quot;')
                .replace(/'/g, '&#39;');
        }

