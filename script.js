        // Donut chart
        function renderDonut() {
            const skills = gSkills();
            if (!skills) return;
            const total = Object.values(skills).reduce((sum, s) => sum + s.repos, 0);
            const colors = { 'Shell': '#4ecdc4', 'Python': '#3776ab', 'JavaScript': '#f7df1e', 'TypeScript': '#3178c6', 'HTML': '#e34c26', 'CSS': '#264de4' };
            const langNames = { 'Shell': 'Shell/Bash', 'Python': 'Python', 'JavaScript': 'JavaScript', 'TypeScript': 'TypeScript', 'HTML': 'HTML', 'CSS': 'CSS' };
            const chart = document.getElementById('donut-chart');
            const legend = document.getElementById('donut-legend');
            if (!chart || !legend) return;
            const size = 180, radius = 70, strokeWidth = 25;
            const circumference = 2 * Math.PI * radius;
            let offset = 0;
            let svg = '<svg width="' + size + '" height="' + size + '" viewBox="0 0 ' + size + ' ' + size + '">';
            for (const [lang, data] of Object.entries(skills)) {
                const percentage = data.repos / total;
                const dashLength = percentage * circumference;
                const color = colors[lang] || '#9ca3b4';
                svg += '<circle cx="' + size/2 + '" cy="' + size/2 + '" r="' + radius + '" fill="none" stroke="' + color + '" stroke-width="' + strokeWidth + '" stroke-dasharray="' + dashLength + ' ' + (circumference - dashLength) + '" stroke-dashoffset="' + (-offset) + '" />';
                offset += dashLength;
            }
            svg += '</svg>';
            chart.innerHTML = svg + '<div class="donut-center"><div class="donut-total">' + total + '</div><div class="donut-label">' + (currentLang === 'nl' ? 'Repos' : 'Repos') + '</div></div>';
            legend.innerHTML = Object.entries(skills).map(([lang, data]) => '<div class="legend-item"><div class="legend-color" style="background: ' + (colors[lang] || '#9ca3b4') + ';"></div><span class="legend-label">' + (langNames[lang] || lang) + '</span><span class="legend-value">' + data.repos + ' repos (' + data.percentage + '%)</span></div>').join('');
                    }

