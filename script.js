        function renderContributionHeatmap() {
            const container = document.getElementById('contribution-heatmap');
            if (!container) return;
            
            // Generate last 30 days of activity
            const days = [];
            const today = new Date();
            for (let i = 29; i >= 0; i--) {
                const d = new Date(today);
                d.setDate(d.getDate() - i);
                days.push(d.toISOString().split('T')[0]);
            }
            
            // Count contributions per day from githubData
            const contribCounts = {};
            const contributions = gContributions();
            const repos = gRepos();
            if (contributions) {
                contributions.forEach(c => {
                    const date = c.date.split('T')[0];
                    contribCounts[date] = (contribCounts[date] || 0) + 1;
                });
            }
            
            // Repo-creatie/updates van EIGEN werk meetellen (forks niet: die zeggen
            // niets over jouw activiteit en zouden de heatmap opblazen).
            if (repos) {
                repos.filter(r => r && !r.fork).forEach(r => {
                    const created = r.created ? r.created.split('T')[0] : null;
                    const updated = r.updated ? r.updated.split('T')[0] : null;
                    if (created) contribCounts[created] = (contribCounts[created] || 0) + 1;
                    if (updated) contribCounts[updated] = (contribCounts[updated] || 0) + 1;
                });
            }
            
            // Find max for scaling
            const maxCount = Math.max(...days.map(d => contribCounts[d] || 0), 1);
            
            // Render heatmap
            let html = '<div style="display: grid; grid-template-columns: repeat(10, 1fr); gap: 3px; margin-bottom: 0.5rem;">';
            days.forEach(day => {
                const count = contribCounts[day] || 0;
                const intensity = count / maxCount;
                const opacity = 0.15 + (intensity * 0.85);
                const color = count > 0 ? `rgba(78, 205, 196, ${opacity})` : 'var(--surface2)';
                html += `<div title="${day}: ${count} contributions" style="width: 100%; aspect-ratio: 1; border-radius: 3px; background: ${color};"></div>`;
            });
            html += '</div>';
            
            // Legend
            html += '<div style="display: flex; justify-content: space-between; font-size: 0.7rem; color: var(--text-muted);">';
            html += '<span>30 dagen geleden</span>';
            html += '<span>Vandaag</span>';
            html += '</div>';
            
            // Stats
            const totalContribs = Object.values(contribCounts).reduce((a, b) => a + b, 0);
            const activeDays = Object.keys(contribCounts).length;
            html += `<div style="margin-top: 0.5rem; font-size: 0.8rem; color: var(--text-muted);">`;
            html += `${totalContribs} activiteiten in laatste 30 dagen · ${activeDays} actieve dagen`;
            html += `</div>`;
            
            container.innerHTML = html;
            setSectionTimestamp('heatmap', githubData.generated_at);
        }

